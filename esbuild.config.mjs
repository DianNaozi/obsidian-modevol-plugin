import esbuild from "esbuild";
import process from "process";
import { readFile } from "node:fs/promises";
import builtins from "builtin-modules";
import vue from "@the_tree/esbuild-plugin-vue3"
const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

Mind Elixir (https://github.com/SSShooter/mind-elixir-core)
${await readFile(new URL("./node_modules/mind-elixir/LICENSE", import.meta.url), "utf8")}
*/
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [vue({ isProd: true })],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@types/codemirror",
		...builtins],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
});

const stylesContext = await esbuild.context({
	entryPoints: ['src/styles.css'],
	bundle: true,
	outfile: 'styles.css',
	minify: prod,
	plugins: [{
		name: 'scope-mind-elixir',
		setup(build) {
			build.onLoad({ filter: /MindElixir\.css$/ }, async ({ path }) => ({
				contents: (await readFile(path, 'utf8'))
					.replaceAll('.map-container', '.jiangou-mindmap-view .map-container')
					.replaceAll('.mind-elixir-toolbar', '.jiangou-mindmap-view .mind-elixir-toolbar'),
				loader: 'css',
				resolveDir: process.cwd(),
			}));
		},
	}],
});


if (prod) {
	await Promise.all([context.rebuild(), stylesContext.rebuild()]);
	process.exit(0);
} else {
	await Promise.all([context.watch(), stylesContext.watch()]);
}